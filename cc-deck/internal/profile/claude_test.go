// TestResolveRejectsClearedSource verifies that an env source reading a
// variable the wrapper clears for the profile's kind is rejected, because the
// credential check would always fail.
func TestResolveRejectsClearedSource(t *testing.T) {
	a := agent.Get("claude")
	require.NotNil(t, a)
	p := config.Profile{
		Harness: "claude",
		Auth:    &config.AuthConfig{OAuthToken: &config.CredentialSource{Env: "ANTHROPIC_API_KEY"}},
	}
	_, err := profile.Resolve("private", p, a)
	require.Error(t, err)
	assert.Contains(t, err.Error(), `auth.oauth_token reads "ANTHROPIC_API_KEY", which the wrapper clears`)

	// Reading the profile's own kind variable is fine.
	p.Auth = &config.AuthConfig{APIKey: &config.CredentialSource{Env: "ANTHROPIC_API_KEY"}}
	_, err = profile.Resolve("work", p, a)
	assert.NoError(t, err)
}

// TestClaudeRenderGolden_EnvEntries verifies user env entries are rendered
// in sorted order with single-quoted values.
func TestClaudeRenderGolden_EnvEntries(t *testing.T) {
	a := agent.Get("claude")
	require.NotNil(t, a)

	tr, ok := profile.Lookup("claude")
	require.True(t, ok)

	rp := profile.ResolvedProfile{
		Name:    "custom",
		Harness: a,
		Backend: config.BackendAnthropic,
		Model:   "claude-sonnet-5",
		Login:   true,
		Env: map[string]string{
			"ZEBRA_VAR": "last",
			"ALPHA_VAR": "first",
		},
		BinDir: "/tmp/test-bin",
	}

	ws, err := tr.Render(rp)
	require.NoError(t, err)

	script := string(ws.Content)

	// Env entries must appear sorted by key
	alphaIdx := strings.Index(script, `export ALPHA_VAR='first'`)
	zebraIdx := strings.Index(script, `export ZEBRA_VAR='last'`)
	assert.Greater(t, alphaIdx, -1, "ALPHA_VAR must appear")
	assert.Greater(t, zebraIdx, -1, "ZEBRA_VAR must appear")
	assert.Less(t, alphaIdx, zebraIdx, "env entries must be sorted by key")
}

