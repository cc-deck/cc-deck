// renderClaude renders rp with the registered Claude translator.
func renderClaude(t *testing.T, rp profile.ResolvedProfile) profile.WrapperScript {
	t.Helper()
	a := agent.Get("claude")
	require.NotNil(t, a)
	tr, ok := profile.Lookup("claude")
	require.True(t, ok)
	rp.Harness = a
	ws, err := tr.Render(rp)
	require.NoError(t, err)
	return ws
}

// TestClaudeRenderGolden_EnvSource verifies the wrapper script layout for
// a Claude profile with an env-sourced API key on the Anthropic backend.
// This mirrors the first contract example in contracts/wrapper-script.md.
func TestClaudeRenderGolden_EnvSource(t *testing.T) {
	ws := renderClaude(t, profile.ResolvedProfile{
		Name:    "work",
		Backend: config.BackendAnthropic,
		Model:   "claude-sonnet-5",
		Color:   "#5AC0E2",
		Env:     map[string]string{"ANTHROPIC_DEFAULT_HAIKU_MODEL": "claude-haiku-4-5-20251001"},
		APIKey:  &config.CredentialSource{Env: "ANTHROPIC_API_KEY_WORK"},
		BinDir:  "/tmp/test-bin",
	})

	assert.Equal(t, "claude-work", ws.Name)
	assert.Equal(t, uint32(0755), ws.Mode)
	assert.Equal(t, `#!/bin/sh
# generated by cc-deck profile work; do not edit
export CC_DECK_PROFILE='work'
export CC_DECK_PROFILE_COLOR='#5AC0E2'
export CC_DECK_PROFILE_ICON=''
unset CLAUDE_CODE_OAUTH_TOKEN CLAUDE_CODE_USE_BEDROCK CLAUDE_CODE_USE_VERTEX
export CLAUDE_CONFIG_DIR="$HOME/.local/share/cc-deck/profiles/work/claude"
export ANTHROPIC_MODEL='claude-sonnet-5'
export ANTHROPIC_DEFAULT_HAIKU_MODEL='claude-haiku-4-5-20251001'
if [ -z "${ANTHROPIC_API_KEY_WORK:-}" ]; then
  echo "cc-deck profile 'work': credential ANTHROPIC_API_KEY_WORK is not available" >&2
  exit 1
fi
export ANTHROPIC_API_KEY="$ANTHROPIC_API_KEY_WORK"
exec claude "$@"
`, string(ws.Content))
}

