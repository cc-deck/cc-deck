// TestClaudeRenderGolden_SecretSourceErrors verifies that secret-sourced
// credentials produce an error (not renderable outside Kubernetes).
func TestClaudeRenderGolden_SecretSourceErrors(t *testing.T) {
	a := agent.Get("claude")
	require.NotNil(t, a)

	tr, ok := profile.Lookup("claude")
	require.True(t, ok)

	t.Run("api_key_secret", func(t *testing.T) {
		rp := profile.ResolvedProfile{
			Name:    "secret-test",
			Harness: a,
			Backend: config.BackendAnthropic,
			APIKey:  &config.CredentialSource{Secret: "my-secret"},
			BinDir:  "/tmp/test-bin",
		}
		_, err := tr.Render(rp)
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "secret source is not renderable")
	})

	t.Run("credentials_secret", func(t *testing.T) {
		rp := profile.ResolvedProfile{
			Name:        "secret-test",
			Harness:     a,
			Backend:     config.BackendVertex,
			Credentials: &config.CredentialSource{Secret: "my-secret"},
			BinDir:      "/tmp/test-bin",
		}
		_, err := tr.Render(rp)
		assert.Error(t, err)
		assert.Contains(t, err.Error(), "secret source is not renderable")
	})
}
