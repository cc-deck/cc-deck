// TestOpenCodeRenderGolden_OpenAIEnvSource verifies the wrapper script layout
// for an OpenCode profile with an env-sourced API key on the OpenAI backend.
func TestOpenCodeRenderGolden_OpenAIEnvSource(t *testing.T) {
	a := agent.Get("opencode")
	require.NotNil(t, a)

	tr, ok := profile.Lookup("opencode")
	require.True(t, ok)

	rp := profile.ResolvedProfile{
		Name:    "dev",
		Harness: a,
		Backend: config.BackendOpenAI,
		Model:   "gpt-4o",
		APIKey:  &config.CredentialSource{Env: "OPENAI_API_KEY_DEV"},
		BinDir:  "/tmp/test-bin",
	}

	ws, err := tr.Render(rp)
	require.NoError(t, err)

	assert.Equal(t, "opencode-dev", ws.Name)
	assert.Equal(t, uint32(0755), ws.Mode)

	script := string(ws.Content)

	// Structural checks
	lines := strings.Split(script, "\n")
	assert.Equal(t, "#!/bin/sh", lines[0], "line 1 must be the shebang")
	assert.Equal(t, "# generated by cc-deck profile dev; do not edit", lines[1], "line 2 must be the marker")
	assert.Equal(t, "export CC_DECK_PROFILE='dev'", lines[2], "line 3 must export CC_DECK_PROFILE")

	// OPENCODE_CONFIG points at the JSON file, not a directory
	assert.Contains(t, script, `export OPENCODE_CONFIG="$HOME/.local/share/cc-deck/profiles/dev/opencode/opencode.json"`)

	// OpenCode does NOT export model in the wrapper; it writes to opencode.json
	assert.NotContains(t, script, "gpt-4o")

	// Credential env check: OpenAI backend uses OPENAI_API_KEY
	assert.Contains(t, script, `if [ -z "${OPENAI_API_KEY_DEV:-}" ]; then`)
	assert.Contains(t, script, `echo "cc-deck profile 'dev': credential OPENAI_API_KEY_DEV is not available" >&2`)
	assert.Contains(t, script, `exit 1`)
	assert.Contains(t, script, `export OPENAI_API_KEY="$OPENAI_API_KEY_DEV"`)
	assert.Contains(t, script, `exec opencode "$@"`)

	// The exec line must be the last non-empty line
	trimmed := strings.TrimRight(script, "\n")
	lastLine := trimmed[strings.LastIndex(trimmed, "\n")+1:]
	assert.Equal(t, `exec opencode "$@"`, lastLine)
}

// TestOpenCodeRenderGolden_AnthropicEnvSource verifies the wrapper script
// layout for an OpenCode profile using the Anthropic backend. The credential
