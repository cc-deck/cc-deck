// TestOpenCodeRenderGolden_EnvEntries verifies user env entries are rendered
// in sorted order for OpenCode.
func TestOpenCodeRenderGolden_EnvEntries(t *testing.T) {
	a := agent.Get("opencode")
	require.NotNil(t, a)

	tr, ok := profile.Lookup("opencode")
	require.True(t, ok)

	rp := profile.ResolvedProfile{
		Name:    "envtest",
		Harness: a,
		Backend: config.BackendOpenAI,
		APIKey:  &config.CredentialSource{Env: "KEY_VAR"},
		Env: map[string]string{
			"BETA":  "b",
			"ALPHA": "a",
		},
		BinDir: "/tmp/test-bin",
	}

	ws, err := tr.Render(rp)
	require.NoError(t, err)

	script := string(ws.Content)

	alphaIdx := strings.Index(script, `export ALPHA='a'`)
	betaIdx := strings.Index(script, `export BETA='b'`)
	assert.Greater(t, alphaIdx, -1, "ALPHA must appear")
	assert.Greater(t, betaIdx, -1, "BETA must appear")
	assert.Less(t, alphaIdx, betaIdx, "env entries must be sorted by key")
}

// TestOpenCodeRenderGolden_SecretSourceErrors verifies that secret-sourced
