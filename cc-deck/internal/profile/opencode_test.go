	assert.Contains(t, script, `export OPENCODE_CONFIG="$HOME/.local/share/cc-deck/profiles/anthro/opencode/opencode.json"`)

	// Anthropic backend maps API key to ANTHROPIC_API_KEY
	assert.Contains(t, script, `if [ -z "${ANTHROPIC_API_KEY_ANTHRO:-}" ]; then`)
